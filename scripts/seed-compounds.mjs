// Generates SQL to seed the public.compounds table from the app's bundled
// src/data/compounds.js, so the CMS has rows to edit. One-time.
//
//   node scripts/seed-compounds.mjs > /tmp/seed-compounds.sql
//   # then paste /tmp/seed-compounds.sql into the Supabase SQL editor, or:
//   # psql "$DATABASE_URL" -f /tmp/seed-compounds.sql
//
// Idempotent: upserts on id, so re-running refreshes from the bundle. After
// seeding, edits in the dashboard win (they overwrite the row); re-running this
// would overwrite them again — so only re-run to reset to the bundled baseline.
import { pathToFileURL } from 'node:url'

const COMPOUNDS_PATH = '/Users/jettarch/Projects/bluprint-health/src/data/compounds.js'

const { compounds } = await import(pathToFileURL(COMPOUNDS_PATH).href)
if (!Array.isArray(compounds)) {
  console.error('Could not load compounds array from', COMPOUNDS_PATH)
  process.exit(1)
}

const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const jb = (obj) => `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`

const rows = compounds.map((c, i) => {
  return `(${q(c.id)}, ${q(c.name)}, ${q(c.primaryCategory)}, ${q(c.researchStatusBadge)}, ` +
    `${q(c.oneLiner)}, ${q(c.legalStatus)}, false, ${jb(c)}, ${i})`
})

console.log('-- Seed public.compounds from the bundled src/data/compounds.js')
console.log('-- Generated by bluprint-admin/scripts/seed-compounds.mjs')
console.log('insert into public.compounds')
console.log('  (id, name, primary_category, research_status_badge, one_liner, legal_status, hidden, data, sort)')
console.log('values')
console.log(rows.join(',\n'))
console.log(`on conflict (id) do update set
  name = excluded.name,
  primary_category = excluded.primary_category,
  research_status_badge = excluded.research_status_badge,
  one_liner = excluded.one_liner,
  legal_status = excluded.legal_status,
  data = excluded.data,
  sort = excluded.sort,
  updated_at = now();`)
console.error(`-- ${rows.length} compounds prepared`)
